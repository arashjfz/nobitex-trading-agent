const DICTS: Record<Locale, Dict> = { en: EN, fa: FA, ar: AR, de: DE };

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly locales = LOCALES;
  readonly locale = signal<Locale>(this.initialLocale());
  readonly dir = computed<'ltr' | 'rtl'>(() =>
    this.locale() === 'fa' || this.locale() === 'ar' ? 'rtl' : 'ltr',
  );
  readonly intl = computed(() => this.option().intl);

  private readonly dict = computed(() => DICTS[this.locale()]);

  constructor() {
    effect(() => {
      const locale = this.locale();
      document.documentElement.lang = locale;
      document.documentElement.dir = this.dir();
    });
  }

  option(): LocaleOption {
    return LOCALES.find((item) => item.code === this.locale()) ?? LOCALES[0];
  }

  t(key: string, params?: Record<string, string | number>, fallback?: string): string {
    const dict: Record<string, string> = this.dict();
    const en: Record<string, string> = EN;
    let text = dict[key] ?? en[key] ?? fallback ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  }

  has(key: string): boolean {
    const dict: Record<string, string> = this.dict();
    const en: Record<string, string> = EN;
    return key in dict || key in en;
  }

  setLocale(locale: Locale): void {
    this.locale.set(locale);
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // Storage can be unavailable in private mode; the in-memory locale still works.
    }
  }

  private initialLocale(): Locale {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (this.isLocale(saved)) {
        return saved;
      }
    } catch {
      // Ignore storage errors and fall back to the browser language.
    }
    const browser = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return this.isLocale(browser) ? browser : 'en';
  }

  private isLocale(value: string | null | undefined): value is Locale {
    return value === 'en' || value === 'fa' || value === 'ar' || value === 'de';
  }
}
